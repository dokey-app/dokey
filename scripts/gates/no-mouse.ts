import { type Gate, pending, runGate } from './gate.ts';

// Предмет гейта вводит срез Э-1; до него гейт существует адресом и возвращает «пусто»
// (implementation-plan §2.2). Зелёный от «проверено» отличается словом ПУСТО в выводе.
//
// Условий два (D-101):
//   1. доля сценариев-фикстур, проходимых без мыши, ≥ 60 % (NFR-08, единица задана D-75);
//   2. глубина до любой позиции реестра ≤ 2 нажатий (половина NFR-05, D-73 п. 4). Список
//      позиций берётся из реестра, а не пишется руками, — иначе новая позиция проходит
//      проверку молча.
// Вторая половина NFR-05 — клиентский переход ≤ 300 мс — живёт в G-01: это порог скорости.
export const gate: Gate = {
  id: 'G-11',
  command: 'gate:nomouse',
  claim: 'клавиатурная достижимость: доля без мыши и глубина до инструмента',
  enabledIn: 'Э-1',
  run: () => pending('Э-1'),
};

if (import.meta.filename === process.argv[1]) await runGate(gate);
