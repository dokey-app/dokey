import { type Gate, pending, runGate } from './gate.ts';

// Предмет гейта вводит срез Э-1; до него гейт существует адресом и возвращает «пусто»
// (implementation-plan §2.2). Зелёный от «проверено» отличается словом ПУСТО в выводе.
//
// Условий два (D-95, ИНВ-01):
//   1. отрицательное — сторонних origin в релизной сборке ноль (считается из артефакта);
//   2. положительное — в прогоне RUN-11 с токеном-фикстурой ни один URL, заголовок и тело
//      запроса не содержат подстроки фикстуры, НЕЗАВИСИМО от origin. Без него отправка ввода
//      на уже разрешённый /s/event проходит первое условие и не меняет счётчик ENT-24.
// Второе условие получает предмет вместе с корпусом фикстур и до тех пор возвращает «пусто»
// отдельно от первого.
export const gate: Gate = {
  id: 'G-04',
  command: 'gate:egress',
  claim: 'сторонних origin ноль и ввод не уходит ни на один адрес',
  enabledIn: 'Э-1',
  run: () => pending('Э-1'),
};

if (import.meta.filename === process.argv[1]) await runGate(gate);
